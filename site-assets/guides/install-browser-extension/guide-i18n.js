const SUPPORTED_LOCALES = ["zh-CN", "en", "ja", "ko"];
const textSources = [];
const attributeSources = [];

function normalizeLocale(value) {
  const raw = String(value || "").toLowerCase();
  if (raw === "zh" || raw.startsWith("zh-")) return "zh-CN";
  if (raw === "en" || raw.startsWith("en-")) return "en";
  if (raw === "ja" || raw.startsWith("ja-")) return "ja";
  if (raw === "ko" || raw.startsWith("ko-")) return "ko";
  return "";
}

function translate(source, locale) {
  if (locale === "zh-CN") return source;
  return GUIDE_MESSAGES[locale]?.[source] || source;
}

function rememberSources() {
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (node.parentElement?.closest("[data-guide-locale]")) continue;
    const source = node.textContent?.trim();
    if (
      source &&
      (/[\u3400-\u9fff]/u.test(source) || ["。", "、"].includes(source))
    ) {
      textSources.push([node, source]);
    }
  }
  for (const element of document.querySelectorAll("[aria-label]")) {
    const source = element.getAttribute("aria-label");
    if (source) attributeSources.push([element, source]);
  }
}

function replaceText(node, value) {
  const current = node.textContent || "";
  const leading = current.match(/^\s*/u)?.[0] || "";
  const trailing = current.match(/\s*$/u)?.[0] || "";
  node.textContent = `${leading}${value}${trailing}`;
}

function localizeLinks(locale) {
  for (const link of document.querySelectorAll("[data-guide-local-link]")) {
    const base = link.dataset.guideBaseHref || link.getAttribute("href");
    if (!base) continue;
    link.dataset.guideBaseHref = base;
    const url = new URL(base, window.location.origin);
    if (locale === "en") url.searchParams.delete("lang");
    else url.searchParams.set("lang", locale);
    link.setAttribute("href", `${url.pathname}${url.search}${url.hash}`);
  }
  const parent = document.querySelector("[data-agentmesh-link]");
  if (parent) {
    parent.setAttribute("href", {
      "zh-CN": "https://agentmesh360.com/zh/",
      en: "https://agentmesh360.com/",
      ja: "https://agentmesh360.com/ja/",
      ko: "https://agentmesh360.com/ko/"
    }[locale]);
  }
}

export function applyGuideLocale(locale, { updateUrl = false } = {}) {
  const selected = SUPPORTED_LOCALES.includes(locale) ? locale : "en";
  document.documentElement.lang = selected;
  for (const [node, source] of textSources) replaceText(node, translate(source, selected));
  for (const [element, source] of attributeSources) {
    element.setAttribute("aria-label", translate(source, selected));
  }
  document.title = translate("安装 AgentMesh-OfficialRecruitment 浏览器扩展", selected);
  document.querySelector('meta[name="description"]')?.setAttribute(
    "content",
    translate("通过 Chrome Web Store 或 AgentMesh360 官方 ZIP 安装 AgentMesh-OfficialRecruitment 浏览器扩展。", selected)
  );
  for (const button of document.querySelectorAll("[data-guide-locale]")) {
    const active = button.dataset.guideLocale === selected;
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", String(active));
  }
  localizeLinks(selected);
  try {
    window.localStorage.setItem("am_locale", selected);
  } catch {
    // The URL remains available when preference storage is restricted.
  }
  if (updateUrl) {
    const url = new URL(window.location.href);
    if (selected === "en") url.searchParams.delete("lang");
    else url.searchParams.set("lang", selected);
    window.history.replaceState(null, "", `${url.pathname}${url.search}${url.hash}`);
  }
}

if (document.body) {
  rememberSources();
  const requested = normalizeLocale(new URLSearchParams(window.location.search).get("lang"));
  let stored = "";
  try {
    stored = normalizeLocale(window.localStorage.getItem("am_locale"));
  } catch {
    // Use the URL or English default when storage is restricted.
  }
  applyGuideLocale(requested || stored || "en");
  for (const button of document.querySelectorAll("[data-guide-locale]")) {
    button.addEventListener("click", () => {
      applyGuideLocale(button.dataset.guideLocale, { updateUrl: true });
    });
  }
}
