export function resolveLocale(query, saved) {
  return Object.hasOwn(PRIVACY_MESSAGES, query) ? query : Object.hasOwn(PRIVACY_MESSAGES, saved) ? saved : 'en';
}
export function renderPrivacy(locale, doc = document) {
  const m = PRIVACY_MESSAGES[locale];
  doc.documentElement.lang = locale;
  doc.title = `${m.title} · AgentMesh-OfficialRecruitment`;
  for (const key of ['title','intro','updated','workbench','home','support','language']) {
    doc.querySelectorAll(`[data-privacy="${key}"]`).forEach(node => { node.textContent = m[key]; });
  }
  doc.querySelector('nav').setAttribute('aria-label',m.nav);
  const article = doc.querySelector('#privacy-sections'); article.replaceChildren();
  for (const [heading,body] of m.sections) {
    const section=doc.createElement('section'), h=doc.createElement('h2'), p=doc.createElement('p');
    h.textContent=heading; p.textContent=body; section.append(h,p); article.append(section);
  }
  doc.querySelector('#privacy-language').value=locale;
  const suffix=locale==='en'?'':`?lang=${locale}`;
  doc.querySelectorAll('a[data-workspace]').forEach(link=>link.setAttribute('href','/app/'+suffix));
  doc.querySelectorAll('a[data-home]').forEach(link=>link.setAttribute('href',locale==='en'?'/':locale==='zh-CN'?'/zh/':`/${locale}/`));
}
if (typeof document !== 'undefined') {
  let saved=null; try { saved=localStorage.getItem('workbench.language'); } catch {}
  renderPrivacy(resolveLocale(new URL(location.href).searchParams.get('lang'), saved));
  document.querySelector('#privacy-language').addEventListener('change', event=>{
    const locale=event.target.value; renderPrivacy(locale);
    try { localStorage.setItem('workbench.language',locale); } catch {}
    const url=new URL(location.href); if(locale==='en')url.searchParams.delete('lang');else url.searchParams.set('lang',locale);
    history.replaceState(null,'',url);
  });
}
